// Helper function to get cities by state code
export const getCitiesByState = (stateCode: string): BrazilianCity[] => {
  return brazilianCities.filter(city => city.stateCode === stateCode).sort((a, b) => a.name.localeCompare(b.name));
};

// Helper function to search cities
export const searchCities = (query: string, stateCode?: string): BrazilianCity[] => {
  const normalizedQuery = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  let cities = stateCode ? getCitiesByState(stateCode) : brazilianCities;
  
  return cities.filter(city => {
    const normalizedName = city.name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    return normalizedName.includes(normalizedQuery);
  }).slice(0, 50); // Limit results for performance
};

// Helper function to get state by code
export const getStateByCode = (code: string): BrazilianState | undefined => {
  return brazilianStates.find(state => state.code === code);
};

